/**
 * css.ts — turn a SynthState into the stylesheet a consumer actually pastes.
 *
 * Two rules govern the output, and the old synthesizer broke both.
 *
 * 1. **Only base tokens are emitted.** In v3 the compound tokens — every glow,
 *    gradient, focus ring and shadow — are already composed at `:root` from
 *    `var(--accent-primary-rgb)` and friends. Overriding a base token
 *    re-substitutes all of them for free. The old tool emitted forty lines of
 *    derived tokens with the channels baked in, which froze them at the values
 *    they had at export time and contradicted the library's central claim right
 *    on the page where it was being sold.
 *
 * 2. **Only what changed is emitted.** A theme that moves two accents should be
 *    four lines long. Dumping the entire token set as an "override" file buries
 *    the two decisions the user made in eighty they didn't.
 */
import {
  COLOR_GROUPS,
  DEFAULT_COLORS,
  DEFAULT_FONTS,
  DEFAULT_RANGES,
  FONT_ROLES,
  RANGE_CONTROLS,
  hexToChannels,
  type SynthState,
  type ThemeMode,
} from './schema';

export interface EmitOptions {
  /** Selector for the dark/base block. `:root` for export, `:root:root` live. */
  root?: string;
  /** Emit every token, not just the ones that differ from the defaults. */
  full?: boolean;
  /** Include the explanatory header comment. */
  header?: boolean;
}

type Line = string;

function colorDecls(state: SynthState, mode: ThemeMode, full: boolean, indent: string): Line[] {
  const out: Line[] = [];
  for (const group of COLOR_GROUPS) {
    const rows: Line[] = [];
    for (const c of group.controls) {
      const value = state.colors[mode][c.token];
      if (!full && value === DEFAULT_COLORS[mode][c.token]) continue;
      const [r, g, b] = hexToChannels(value);
      rows.push(`${indent}${c.token}: rgb(${r}, ${g}, ${b});`);
      if (c.rgb) rows.push(`${indent}${c.token}-rgb: ${r}, ${g}, ${b};`);
    }
    if (rows.length) {
      out.push(`${indent}/* ${group.label} */`, ...rows, '');
    }
  }
  if (out.length) out.pop();
  return out;
}

function fontDecls(state: SynthState, full: boolean): Line[] {
  const rows: Line[] = [];
  for (const role of FONT_ROLES) {
    const keys = [`--font-${role.role}-family`, `--font-${role.role}-fallback`, `--font-${role.role}-weight`];
    const moved = keys.filter((k) => full || state.fonts[k] !== DEFAULT_FONTS[k]);
    if (!moved.length) continue;
    for (const k of moved) rows.push(`  ${k}: ${state.fonts[k]};`);
  }
  return rows.length ? ['  /* Font roles */', ...rows] : [];
}

function rangeDecls(state: SynthState, full: boolean): Line[] {
  const byGroup = new Map<string, Line[]>();
  for (const c of RANGE_CONTROLS) {
    const value = state.ranges[c.token];
    if (!full && value === DEFAULT_RANGES[c.token]) continue;
    const label = groupLabelFor(c.token);
    if (!byGroup.has(label)) byGroup.set(label, []);
    byGroup.get(label)!.push(`  ${c.token}: ${value}${c.unit};`);
  }
  const out: Line[] = [];
  for (const [label, rows] of byGroup) out.push(`  /* ${label} */`, ...rows, '');
  if (out.length) out.pop();
  return out;
}

function groupLabelFor(token: string): string {
  if (token.startsWith('--space-')) return 'Spacing';
  if (token.startsWith('--radius-')) return 'Radii';
  if (token.startsWith('--duration-')) return 'Motion';
  if (token.startsWith('--max-width') || token === '--nav-height') return 'Layout';
  return 'Type scale';
}

const HEADER = `/* ─────────────────────────────────────────────────────────────
 * ARC UI theme — generated by the Theme Synthesizer
 * https://arcui.dev/synth
 *
 * Load this after ARC UI's own stylesheet. Only the base tokens
 * you changed are here: gradients, glows, focus rings and shadows
 * compose from these at :root, so they re-derive on their own.
 * ───────────────────────────────────────────────────────────── */`;

/** The stylesheet, ready to paste. */
export function emitCSS(state: SynthState, opts: EmitOptions = {}): string {
  const { root = ':root', full = false, header = true } = opts;

  const dark = [...colorDecls(state, 'dark', full, '  '), ...blank(fontDecls(state, full)), ...blank(rangeDecls(state, full))];
  const light = colorDecls(state, 'light', full, '  ');

  const blocks: string[] = [];
  if (header && root === ':root') blocks.push(HEADER);

  if (dark.length) blocks.push(`${root} {\n${trim(dark).join('\n')}\n}`);

  if (light.length) {
    const body = trim(light).join('\n');
    blocks.push(`${root}[data-theme="light"] {\n${body}\n}`);
    // `auto` follows the OS. Without this block a generated light theme simply
    // never appears for the people who never touched the toggle — which is
    // most of them, since `auto` is the default.
    blocks.push(
      `@media (prefers-color-scheme: light) {\n  ${root}[data-theme="auto"] {\n${indentBy(body, '  ')}\n  }\n}`,
    );
  }

  if (!blocks.length || (blocks.length === 1 && header)) {
    return `${HEADER}\n\n/* Nothing changed yet — every token still matches the ARC UI defaults. */`;
  }
  return blocks.join('\n\n');
}

/** The same theme as a token object, for consumers who generate their own CSS. */
export function emitJSON(state: SynthState, full = false): string {
  const colors: Record<string, Record<string, string>> = {};
  for (const mode of ['dark', 'light'] as ThemeMode[]) {
    const entries: Record<string, string> = {};
    for (const group of COLOR_GROUPS) {
      for (const c of group.controls) {
        const v = state.colors[mode][c.token];
        if (!full && v === DEFAULT_COLORS[mode][c.token]) continue;
        entries[c.token] = v;
      }
    }
    if (Object.keys(entries).length) colors[mode] = entries;
  }

  const fonts: Record<string, string> = {};
  for (const [k, v] of Object.entries(state.fonts)) {
    if (full || v !== DEFAULT_FONTS[k]) fonts[k] = v;
  }

  const ranges: Record<string, string> = {};
  for (const c of RANGE_CONTROLS) {
    const v = state.ranges[c.token];
    if (!full && v === DEFAULT_RANGES[c.token]) continue;
    ranges[c.token] = `${v}${c.unit}`;
  }

  const payload: Record<string, unknown> = { $schema: 'https://arcui.dev/theme.schema.json' };
  if (Object.keys(colors).length) payload.colors = colors;
  if (Object.keys(fonts).length) payload.fonts = fonts;
  if (Object.keys(ranges).length) payload.scale = ranges;

  return JSON.stringify(payload, null, 2);
}

/* ── helpers ── */

function blank(lines: Line[]): Line[] {
  return lines.length ? ['', ...lines] : [];
}

function trim(lines: Line[]): Line[] {
  const out = [...lines];
  while (out.length && out[0] === '') out.shift();
  while (out.length && out[out.length - 1] === '') out.pop();
  return out;
}

function indentBy(body: string, pad: string): string {
  return body
    .split('\n')
    .map((l) => (l ? pad + l : l))
    .join('\n');
}
