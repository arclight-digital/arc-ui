#!/usr/bin/env node
/**
 * check-hand-authored-wrappers.js
 *
 * A wrapper prism did not write is registered here, with its reason, and still
 * exposes its element when the component has public methods.
 *
 * prism emits a handle wherever a component has public methods, and fails
 * `--strict` on a missing one (test-frame §4.2, #94). It refuses to touch a file
 * without its header, correctly: its own source says "manual file, not ours
 * to judge". So a hand-authored wrapper gets no handle and no finding. That's
 * the silent direction every framed defect in test-frame.md went.
 * arc-virtual-list's six hand-authored wrappers had exactly this: the component
 * has `scrollToIndex()`, and only Svelte's `bind:this` and Angular's host
 * reached the element. React, Vue, Preact and Solid consumers could not call it.
 *
 * Rules:
 *   1. Every wrapper source file without prism's header is in MANUAL, with a
 *      reason. A new one is a decision, not an accident.
 *   2. A manual wrapper whose component has public methods exposes the element,
 *      the way the generated wrappers do for that framework.
 *   3. A MANUAL entry that no longer names a hand-authored file is stale.
 *
 * Run via: pnpm check hand-authored-wrappers (and as part of pnpm generate)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const FRAMEWORKS = ['react', 'vue', 'svelte', 'solid', 'preact', 'angular'];
const HEADER = 'Auto-generated by @arclux/prism';

const VIRTUAL_LIST =
  'virtualization: only the framework can create its own rows, so the wrapper owns them ' +
  '(see the file header). prism writes a pass-through, which cannot.';

/** Repo-relative path → why it is hand-authored. */
const MANUAL = {
  'packages/react/src/create-component.ts':
    'shared helper the React wrappers are built with, not a component wrapper',
  'packages/react/src/content/VirtualList.ts': VIRTUAL_LIST,
  'packages/vue/src/content/VirtualList.vue': VIRTUAL_LIST,
  'packages/svelte/src/content/VirtualList.svelte': VIRTUAL_LIST,
  'packages/solid/src/content/VirtualList.tsx': VIRTUAL_LIST,
  'packages/preact/src/content/VirtualList.tsx': VIRTUAL_LIST,
  'packages/angular/src/content/VirtualList.ts': VIRTUAL_LIST,
};

/** How each framework's generated wrappers hand out the element. */
const EXPOSES = {
  react: /useImperativeHandle\(/,
  preact: /useImperativeHandle\(/,
  vue: /defineExpose\(\s*\{\s*element\b/,
  svelte: /export function element\(/,
  solid: /local\.ref\b/,
  angular: /get element\(\)/,
};

const manifest = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'packages/web-components/custom-elements.json'), 'utf8'),
);
const methodsOf = new Map();
for (const mod of manifest.modules) {
  for (const d of mod.declarations ?? []) {
    if (!d.tagName) continue;
    const methods = (d.members ?? []).filter(
      (m) =>
        m.kind === 'method' &&
        (m.privacy ?? 'public') === 'public' &&
        !m.static &&
        !m.name.startsWith('_'),
    );
    methodsOf.set(
      d.tagName,
      methods.map((m) => m.name),
    );
  }
}

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p);
    return /\.(ts|tsx|vue|svelte)$/.test(e.name) &&
      !e.name.endsWith('.d.ts') &&
      e.name !== 'index.ts'
      ? [p]
      : [];
  });

const failures = [];
const found = new Set();

for (const fw of FRAMEWORKS) {
  for (const file of walk(path.join(ROOT, 'packages', fw, 'src'))) {
    const rel = path.relative(ROOT, file);
    const src = fs.readFileSync(file, 'utf8');
    if (
      src
        .split('\n')
        .slice(0, 3)
        .some((l) => l.includes(HEADER))
    )
      continue;
    found.add(rel);
    if (!MANUAL[rel]) {
      failures.push(
        `${rel}\n      hand-authored (no prism header) and not in MANUAL: add it, with the reason`,
      );
      continue;
    }
    const tag = src.match(/@arclux\/arc-ui\/([a-z-]+)/)?.[1];
    const methods = tag ? (methodsOf.get(`arc-${tag}`) ?? []) : [];
    if (methods.length && !EXPOSES[fw].test(src)) {
      failures.push(
        `${rel}\n      <arc-${tag}> has public methods (${methods.join(', ')}) and this wrapper does not expose the element`,
      );
    }
  }
}

for (const rel of Object.keys(MANUAL)) {
  if (!found.has(rel))
    failures.push(`${rel}\n      MANUAL entry with no hand-authored file: delete it`);
}

if (failures.length) {
  console.error(`check-hand-authored-wrappers: ${failures.length} finding(s)\n`);
  console.error(failures.map((f) => `  ${f}`).join('\n'));
  process.exit(1);
}
console.log(
  `check-hand-authored-wrappers: ${found.size} hand-authored file(s), each registered and exposing its element where it must`,
);
