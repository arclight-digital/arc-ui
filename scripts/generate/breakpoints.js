import { tokens } from '../../shared/tokens.js';
import fs from 'node:fs';

/**
 * Breakpoints as numbers, for the places CSS custom properties cannot reach.
 *
 * A media query cannot read a var(): `@media (max-width: var(--breakpoint-lg))`
 * is simply invalid, and there is no CSS mechanism that makes it work. Nor can
 * a JS width comparison read one without a getComputedStyle round-trip. So the
 * only way for a component's media query and a component's `innerWidth` check
 * to share one source of truth is to hand them the number at build time.
 *
 * Emitted as a JS module for the same reason host-tokens.js is: it has to reach
 * a Lit `css` tagged template, which accepts interpolated numbers but not
 * strings, and plain JS comparisons besides.
 *
 * Values are stripped to unitless numbers — `900px` becomes `900` — because
 * that is what both consumers need: `${nav}px` inside a template, and a bare
 * `> nav` in a comparison.
 */
const entries = Object.entries(tokens.breakpoint)
  .map(([name, value]) => [name, Number.parseFloat(value)]);

const decls = entries
  .map(([name, value]) => `  ${/^[a-z][a-zA-Z0-9]*$/.test(name) ? name : `'${name}'`}: ${value},`)
  .join('\n');

const out = `// Generated by scripts/generate/breakpoints.js — do not edit by hand.
// Edit shared/tokens.js instead, then run \`pnpm generate\`.

/**
 * Breakpoint widths in pixels, unitless.
 *
 * For media queries inside a \`css\` template, interpolate with a unit:
 *   css\`@media (max-width: \${breakpoints.navCollapse}px) { … }\`
 * For width comparisons in JS, use the number directly:
 *   if (window.innerWidth > breakpoints.navCollapse) …
 */
export const breakpoints = {
${decls}
};
`;

fs.writeFileSync('packages/web-components/src/generated/breakpoints.js', out);
console.log('✓ breakpoints.js generated');
