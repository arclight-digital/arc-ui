#!/usr/bin/env node
/**
 * Server-rendered markup for every component with a `list()` prop, captured
 * with the real renderer, for test/hydration-determinism.test.js.
 *
 * A `list()` prop is script-set data (an array has no useful attribute
 * spelling), and a page commonly assigns it before the register barrel
 * upgrades the element. Lit applies those pre-upgrade values at the top of the
 * first update, which is the update that has to adopt the server's markup. The
 * server rendered from attributes alone, so a first client render that uses the
 * page's array is a hydration mismatch, and hydration abandons the tree.
 *
 * The test needs the markup the server really produces (hand-written markup
 * would carry no lit-part markers and prove nothing), and the browser runner
 * cannot run @lit-labs/ssr, so it is captured here, in Node, as part of
 * `pnpm generate`, and diffed like every other generated file.
 *
 * Output: packages/web-components/test/fixtures/ssr-list-props.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const WC = path.join(ROOT, 'packages/web-components');
const SRC = path.join(WC, 'src');
const OUT = path.join(WC, 'test/fixtures/ssr-list-props.js');

const requireFromWC = createRequire(pathToFileURL(path.join(WC, 'package.json')));
const importFromWC = (spec) => import(pathToFileURL(requireFromWC.resolve(spec)).href);
const { render } = await importFromWC('@lit-labs/ssr');
const { collectResult } = await importFromWC('@lit-labs/ssr/lib/render-result.js');
const { html } = await importFromWC('lit');
const markupTemplate = (text) => html(Object.assign([text], { raw: [text] }));

/** Tags with list() props, from each class module's static properties. */
function candidates() {
  const out = [];
  for (const tier of fs.readdirSync(SRC, { withFileTypes: true })) {
    if (!tier.isDirectory() || tier.name === 'icons' || tier.name === 'generated') continue;
    for (const file of fs.readdirSync(path.join(SRC, tier.name))) {
      if (!file.endsWith('.register.js')) continue;
      const reg = fs.readFileSync(path.join(SRC, tier.name, file), 'utf8');
      const tag = reg.match(/customElements\.define\(\s*['"]([a-z0-9-]+)['"]/)?.[1];
      if (!tag) continue;
      const cls = path.join(SRC, tier.name, file.replace('.register.js', '.js'));
      if (!fs.existsSync(cls)) continue;
      const src = fs.readFileSync(cls, 'utf8');
      const props = [...src.matchAll(/^\s+([a-zA-Z]+):\s*list\(/gm)].map((m) => m[1]);
      if (props.length) out.push({ tag, module: path.join(SRC, tier.name, file), props });
    }
  }
  return out.sort((a, b) => a.tag.localeCompare(b.tag));
}

const fixtures = {};
for (const { tag, module, props } of candidates()) {
  await import(pathToFileURL(module).href);
  let markup = await collectResult(render(markupTemplate(`<${tag}></${tag}>`)));
  markup = markup.replace(/^\s*<!--lit-part [^>]*-->/, '').replace(/<!--\/lit-part-->\s*$/, '');
  // Relative to the test, which imports just these rather than the whole
  // register barrel (arc-qr-code's CommonJS dependency does not load there).
  const register = path.relative(path.join(WC, 'test'), module).split(path.sep).join('/');
  fixtures[tag] = { props, register, markup };
}

fs.writeFileSync(
  OUT,
  '// Generated by scripts/generate/ssr-fixtures.js — do not edit by hand.\n' +
    `export default ${JSON.stringify(fixtures, null, 2)};\n`,
);
console.log(`ssr-fixtures: ${Object.keys(fixtures).length} components with list() props`);
