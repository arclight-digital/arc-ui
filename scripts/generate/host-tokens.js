import { generateHostTokensCSS, tokens } from '../../shared/tokens.js';
import fs from 'node:fs';

// The :host static token layer, generated so it cannot drift from the :root one
// in base.css. Both come from shared/tokens.js; see generateHostTokensCSS for the
// three rules that turn a :root value into its :host form.
//
// Emitted as a JS module rather than a .css file because it has to reach a Lit
// `css` tagged template — components adopt a CSSResult into their shadow root,
// and a stylesheet on disk is no use there. Only the resulting string ships; the
// token tree itself stays a build-time dependency.
const decls = generateHostTokensCSS('    ');

const out = `// Generated by scripts/generate-host-tokens.js — do not edit by hand.
// Edit shared/tokens.js instead, then run \`pnpm generate\`.
import { css } from 'lit';

/**
 * The static token layer every component adopts into its shadow root.
 *
 * These are what make a component render correctly with no base.css loaded at
 * all, which is the documented quick start. Colors are deliberately absent: they
 * are themed, and a literal here would pin a component to one theme.
 */
export const hostTokens = css\`
${decls}
\`;

/**
 * Touch targets grow on coarse pointers. Kept separate because it is a media
 * query rather than a declaration list, so it cannot live inside :host { }.
 */
export const hostTouchTokens = css\`
  @media (pointer: coarse) {
    :host {
      --touch-min: ${tokens.touch.mobileMin};
      --touch-pad: ${tokens.touch.mobilePad};
    }
  }
\`;
`;

fs.writeFileSync('packages/web-components/src/generated/host-tokens.js', out);
console.log('✓ host-tokens.js generated');
